export function protectedApplicationRoute(method: string, url: URL, origin: string): boolean {
  if (url.origin !== origin || url.username || url.password) return false;
  const actual = url.pathname.split('/');
  return SECURITY_API_ROUTES.some(([verb, path]) => verb === method && path.split('/').length === actual.length &&
    path.split('/').every((segment, index) => segment.startsWith('{') ? !!actual[index] && !/%2f|%5c/iu.test(actual[index]) : segment === actual[index]));
}
